// Turn one GitHub release into the manifests each package manager wants.
//
//   node tools/release-manifests.mjs <tag> [--out dir]
//
// GitHub Releases stays the single source of artifacts. Every package manager
// below points at the same URLs and the same checksums, so none of them can
// drift from what was actually published, and none of them needs its own build.
//
// The functions are exported and pure so tools/release-manifests.test.mjs can
// cover the version and checksum handling without a network call — publishing a
// wrong checksum to WinGet is not something you find out about quickly.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const REPO = 'neuron-workspace/Neuron';
export const IDENTIFIER = 'NeuronWorkspace.Neuron';
export const HOMEPAGE = 'https://neuron-workspace.github.io/Neuron/';

/**
 * Package-manager versions are not git tags.
 *
 * WinGet, Chocolatey and Homebrew all want a plain version. The tag carries a
 * `v` and, for a prerelease, a suffix those ecosystems either reject outright
 * or sort in ways nobody expects.
 */
export function versionFromTag(tag) {
  const version = String(tag).replace(/^v/, '');
  return { version, base: version.split('-')[0], prerelease: version.includes('-') };
}

/** Whether a release should reach the package managers at all. */
export function shouldPublish(tag) {
  const { prerelease } = versionFromTag(tag);
  // Prereleases go to GitHub and to anyone who opted into them in-app. They do
  // not go to WinGet, Chocolatey or Homebrew: those are where people who did
  // not opt into anything install from.
  return !prerelease;
}

/** The asset a given package manager installs, by filename convention. */
export function pickAsset(assets, kind) {
  const byName = (re) => assets.find((a) => re.test(a.name));
  switch (kind) {
    case 'win-installer':
      // Not the portable build: package managers install and uninstall, which
      // is what the NSIS installer knows how to do.
      return byName(/-win-x64\.exe$/) ?? null;
    case 'mac-arm':
      return byName(/-mac-arm64\.dmg$/) ?? null;
    case 'mac-intel':
      return byName(/-mac-x64\.dmg$/) ?? null;
    default:
      return null;
  }
}

export const sha256 = (buffer) => createHash('sha256').update(buffer).digest('hex');

/**
 * WinGet wants three YAML files under a versioned directory.
 *
 * Written rather than hand-maintained so the version, URL and hash can never
 * disagree with the release they came from.
 */
export function wingetManifests({ version, url, hash }) {
  const header = `# Generated by tools/release-manifests.mjs — do not edit by hand.\n`;
  return {
    [`${IDENTIFIER}.installer.yaml`]: `${header}PackageIdentifier: ${IDENTIFIER}
PackageVersion: ${version}
InstallerType: nullsoft
# No Scope is declared: the NSIS build is still the assisted installer that lets
# the user choose a directory, so it is neither reliably per-user nor per-machine.
# Claiming one would make WinGet promise behaviour the installer does not have.
InstallModes:
  - interactive
  - silent
UpgradeBehavior: install
Installers:
  - Architecture: x64
    InstallerUrl: ${url}
    InstallerSha256: ${hash.toUpperCase()}
ManifestType: installer
ManifestVersion: 1.6.0
`,
    [`${IDENTIFIER}.locale.en-US.yaml`]: `${header}PackageIdentifier: ${IDENTIFIER}
PackageVersion: ${version}
PackageLocale: en-US
Publisher: Neuron Workspace
Author: Shivam Khetan
PublisherUrl: ${HOMEPAGE}
PackageName: Neuron
PackageUrl: ${HOMEPAGE}
License: Apache-2.0
LicenseUrl: https://github.com/${REPO}/blob/main/LICENSE
ShortDescription: A local-first Markdown and MDX knowledge workspace.
Description: Neuron keeps your notes as plain Markdown files on your own disk, with databases, canvases and sandboxed HTML views on top. No account, no telemetry.
Moniker: neuron
Tags:
  - markdown
  - notes
  - knowledge-base
  - local-first
ManifestType: defaultLocale
ManifestVersion: 1.6.0
`,
    [`${IDENTIFIER}.yaml`]: `${header}PackageIdentifier: ${IDENTIFIER}
PackageVersion: ${version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.6.0
`,
  };
}

/** A Chocolatey package: a nuspec plus a script that fetches the same installer. */
export function chocolateyPackage({ version, url, hash }) {
  return {
    'neuron.nuspec': `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/release-manifests.mjs — do not edit by hand. -->
<package xmlns="http://schemas.microsoft.com/packaging/2015/06/nuspec.xsd">
  <metadata>
    <id>neuron</id>
    <version>${version}</version>
    <packageSourceUrl>https://github.com/${REPO}</packageSourceUrl>
    <owners>shiv-khetan</owners>
    <title>Neuron</title>
    <authors>Shivam Khetan</authors>
    <projectUrl>${HOMEPAGE}</projectUrl>
    <licenseUrl>https://github.com/${REPO}/blob/main/LICENSE</licenseUrl>
    <requireLicenseAcceptance>false</requireLicenseAcceptance>
    <projectSourceUrl>https://github.com/${REPO}</projectSourceUrl>
    <docsUrl>${HOMEPAGE}</docsUrl>
    <bugTrackerUrl>https://github.com/${REPO}/issues</bugTrackerUrl>
    <tags>markdown notes knowledge-base local-first electron</tags>
    <summary>A local-first Markdown and MDX knowledge workspace.</summary>
    <description>Neuron keeps your notes as plain Markdown files on your own disk, with databases, canvases and sandboxed HTML views on top. No account, no telemetry.</description>
    <releaseNotes>https://github.com/${REPO}/releases/tag/v${version}</releaseNotes>
  </metadata>
  <files>
    <file src="tools\\**" target="tools" />
  </files>
</package>
`,
    'tools/chocolateyinstall.ps1': `# Generated by tools/release-manifests.mjs — do not edit by hand.
$ErrorActionPreference = 'Stop'

# The checksum is the whole point of this file. Chocolatey downloads over HTTPS
# and then verifies against the hash published with the release, so a package
# built from a swapped binary fails here rather than on a user's machine.
Install-ChocolateyPackage \`
  -PackageName 'neuron' \`
  -FileType 'exe' \`
  -Url64bit '${url}' \`
  -Checksum64 '${hash}' \`
  -ChecksumType64 'sha256' \`
  -SilentArgs '/S' \`
  -ValidExitCodes @(0)
`,
    'tools/chocolateyuninstall.ps1': `# Generated by tools/release-manifests.mjs — do not edit by hand.
$ErrorActionPreference = 'Stop'

$key = Get-ItemProperty -Path @(
  'HKCU:\\Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\*',
  'HKLM:\\Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\*'
) -ErrorAction SilentlyContinue | Where-Object { $_.DisplayName -eq 'Neuron' }

if ($key) {
  Uninstall-ChocolateyPackage -PackageName 'neuron' -FileType 'exe' \`
    -SilentArgs '/S' -File "$($key.UninstallString)"
} else {
  Write-Host 'Neuron is not installed; nothing to remove.'
}
`,
  };
}

/**
 * A Homebrew cask.
 *
 * Both architectures, because a cask that installs the wrong one produces an
 * app that will not open on Apple silicon and no explanation of why.
 */
export function homebrewCask({ version, arm, intel }) {
  return `# Generated by tools/release-manifests.mjs — do not edit by hand.
cask "neuron" do
  arch arm: "arm64", intel: "x64"

  version "${version}"
  sha256 arm:   "${arm.hash}",
         intel: "${intel.hash}"

  url "https://github.com/${REPO}/releases/download/v#{version}/Neuron-#{version}-mac-#{arch}.dmg",
      verified: "github.com/${REPO}/"

  name "Neuron"
  desc "Local-first Markdown and MDX knowledge workspace"
  homepage "${HOMEPAGE}"

  app "Neuron.app"

  # Neuron is signed ad-hoc rather than with a Developer ID, so macOS quarantines
  # it on download. Homebrew removes that attribute for casks it installed
  # itself, which is the supported way past it -- unlike telling a user to run
  # xattr by hand on something they did not build.
  zap trash: [
    "~/Library/Application Support/neuron",
    "~/Library/Preferences/io.github.neuron.notes.plist",
    "~/Library/Saved Application State/io.github.neuron.notes.savedState",
  ]
end
`;
}

// --- CLI --------------------------------------------------------------------

const isMain = import.meta.url.endsWith(String(process.argv[1]).replace(/\\/g, '/'));

if (isMain) {
  const tag = process.argv[2];
  const outIndex = process.argv.indexOf('--out');
  const outDir = outIndex === -1 ? 'release/manifests' : process.argv[outIndex + 1];
  if (!tag) {
    console.error('usage: node tools/release-manifests.mjs <tag> [--out dir]');
    process.exit(1);
  }

  if (!shouldPublish(tag)) {
    console.log(`${tag} is a prerelease; package managers are for stable releases only.`);
    process.exit(0);
  }

  const { version } = versionFromTag(tag);
  const gh = (args) => execFileSync('gh', args, { encoding: 'utf-8', maxBuffer: 32 * 1024 * 1024 });
  const assets = JSON.parse(gh(['release', 'view', tag, '--repo', REPO, '--json', 'assets'])).assets;

  const need = (kind) => {
    const asset = pickAsset(assets, kind);
    if (!asset) throw new Error(`${tag} has no ${kind} asset; nothing to publish.`);
    return asset;
  };

  // Hash the artifacts that were actually published rather than trusting a
  // checksum file: this is the number users' machines will verify against.
  const hashOf = (asset) => {
    const tmp = join(outDir, asset.name);
    gh(['release', 'download', tag, '--repo', REPO, '--pattern', asset.name, '--dir', outDir, '--clobber']);
    return sha256(readFileSync(tmp));
  };

  mkdirSync(outDir, { recursive: true });

  const win = need('win-installer');
  const winHash = hashOf(win);
  const winUrl = `https://github.com/${REPO}/releases/download/${tag}/${win.name}`;

  const wingetDir = join(outDir, 'winget');
  mkdirSync(wingetDir, { recursive: true });
  for (const [name, body] of Object.entries(wingetManifests({ version, url: winUrl, hash: winHash }))) {
    writeFileSync(join(wingetDir, name), body, 'utf-8');
  }

  const chocoDir = join(outDir, 'chocolatey');
  mkdirSync(join(chocoDir, 'tools'), { recursive: true });
  for (const [name, body] of Object.entries(chocolateyPackage({ version, url: winUrl, hash: winHash }))) {
    writeFileSync(join(chocoDir, name), body, 'utf-8');
  }

  const arm = need('mac-arm');
  const intel = need('mac-intel');
  writeFileSync(
    join(outDir, 'neuron.rb'),
    homebrewCask({ version, arm: { hash: hashOf(arm) }, intel: { hash: hashOf(intel) } }),
    'utf-8',
  );

  console.log(`Manifests for ${version} written to ${outDir}`);
}
